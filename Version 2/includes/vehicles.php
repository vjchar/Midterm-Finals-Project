/**
 * Find a vehicle by numeric identifier or slug.
 *
 * @return array<string, mixed>|null
 */
function vehicle_find(string|int $value): ?array
{
    $requestedVehicle = (string) $value;

    foreach (vehicle_all() as $vehicle) {
        if (
            (string) $vehicle["id"] === $requestedVehicle ||
            $vehicle["slug"] === $requestedVehicle
        ) {
            return $vehicle;
        }
    }

    return null;
}
